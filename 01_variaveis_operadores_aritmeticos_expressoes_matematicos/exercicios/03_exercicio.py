"""
Exercício 3: Média de Notas

Um aluno realizou duas provas.

1. A primeira nota foi 7.5 (guarde na variável nota_prova_um).
2. A segunda nota foi 8.5 (guarde na variável nota_prova_dois).

Crie uma terceira variável chamada media_aluno que calcule a média aritmética simples dessas duas notas. Exiba o resultado final usando o comando print(media_aluno).
"""

primeira_nota = 7.5
segunda_nota = 8.5
media_aluno = (primeira_nota + segunda_nota) / 2

print(f"primeira_nota: {primeira_nota}")
print(f"segundo_nota: {segunda_nota}")
print(f"media_aluno: {media_aluno}")