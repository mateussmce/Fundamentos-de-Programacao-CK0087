"""
Exercício 7: prevendo o resultado de expressões

Calcule as expressões abaixo mentalmente, anotando os resultados. Depois execute a célula para conferir.

1 => 2 + 3 * 4    2 => (2 + 3) * 4
3 => 2 ** 3 + 1   4 => 2 ** (3 + 1)
5 => 10 - 4 / 2   6 => (10 - 4) / 2
7 => 10 / 2 * 3   8 => 10 / (2 * 3)
"""

# 1) 2 + 3 * 4 => 2 + 12 = 14
print(f"1) {2} + {3} = {2 + 3 * 4}")

# 2) (2 + 3) * 4 => 5 * 4 = 20
print(f"2) ({2} + {3}) * {4} = {(2 + 3) * 4}")

# 3) 2 ** 3 + 1 => 8 + 1 = 9
print(f"3) {2} ** {3} + {1} = {2 ** 3 + 1}")

# 4) 2 ** (3 + 1) => 2 ** 4 = 16
print(f"4) {2} ** ({3} + {1}) = {2 ** (3 + 1)}")

# 5) 10 - 4 / 2 => 10 - 2 = 8
print(f"5) {10} - {4} / {2} = {10 - 4 / 2}")

# 6) (10 - 4) / 2 => 6 / 2 = 3
print(f"6) ({10} - {4}) / {2} = {(10 - 4) / 2}")

# 7) 10 / 2 * 3 => 5 * 3 = 15
print(f"7) {10} / {2} * {3} = {10 / 2 * 3}")

# 8) 10 / (2 * 3) => 10 / 6 = 1.66666..7
print(f"8) {10} / ({2} * {3}) = {10 / (2 * 3)}")