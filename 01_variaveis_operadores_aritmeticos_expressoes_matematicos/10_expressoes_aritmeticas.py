numero_1 = 4
numero_2 = 10
numero_3 = 12

# 4 / 10 + 12 * 10 => 0,4 + 120 = 120,4
expressao1 = numero_1 / numero_2 + numero_3 * numero_2
print(f"({numero_1} + {numero_2}) / {numero_3 + numero_1} = {expressao2}")

# (4 + 10) / 12 + 4 => 14 / 12 + 4 => 1,66666...7 + 4 = 5,1666...7
expressao2 = (numero_1 + numero_2) / numero_3 + numero_1
print(f"{numero_1} / {numero_2} + {numero_3} * {numero_2} = {expressao1}")
